"""
TFM Framework — Lambda: SendReport
Final state: DeliverReport
Sends the PDF report via Amazon SES (Simple Email Service).
Attaches the PDF from S3 and sends an HTML email with KPI boxes.

Universidad Europea de Madrid · Clara Khabbazi Manzur
Decision D21: HTML email with KPI boxes + PDF attachment
"""

import boto3
import os
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.application import MIMEApplication
from datetime import datetime

s3 = boto3.client('s3', region_name='eu-west-1')
ses = boto3.client('ses', region_name='eu-west-1')

# The sender must be a verified identity in SES. Set SENDER_EMAIL as a Lambda env var;
# defaults to the project owner's verified address for the demo.
SENDER_EMAIL = os.environ.get('SENDER_EMAIL', 'your-email@example.com')

def lambda_handler(event, context):
    """
    Input (from Step Functions):
        event['sector']          — 'energia' or 'telecom'
        event['pdf_key']         — S3 key of the PDF produced by GeneratePDF
        event['recipients']      — list of recipient emails (from the YAML)
        event['stakeholder']     — recipient role label
        event['runtime']['week']

    Output:
        {'status': 'ok', 'recipient': str, 'message_id': str, 'email_sent': bool}
    """
    sector = event['sector']
    pdf_key = event['pdf_key']
    week = event['runtime']['week']
    stakeholder = event.get('stakeholder', '')
    recipients = event.get('recipients', [])

    if not recipients:
        print("WARNING: No recipients configured — skipping email send")
        return {'status': 'skipped', 'recipient': None, 'message_id': None, 'email_sent': False}

    # 1. Download the PDF from the sector bucket
    bucket = f"tfm-{sector}-ckm-ew1"
    pdf_obj = s3.get_object(Bucket=bucket, Key=pdf_key)
    pdf_bytes = pdf_obj['Body'].read()
    pdf_filename = pdf_key.split('/')[-1]

    # 2. Build the HTML email body
    sector_label = sector.title()   # etiqueta genérica (sin rama de sector)
    html_body = build_html_email(sector_label, week, stakeholder)

    # 3. MIME message with the PDF attached
    msg = MIMEMultipart('mixed')
    msg['Subject'] = f"[TFM] Weekly Executive Report — {sector_label} — Week {week}"
    msg['From'] = SENDER_EMAIL
    msg['To'] = ', '.join(recipients)
    msg.attach(MIMEText(html_body, 'html', 'utf-8'))
    pdf_part = MIMEApplication(pdf_bytes, _subtype='pdf')
    pdf_part.add_header('Content-Disposition', 'attachment', filename=pdf_filename)
    msg.attach(pdf_part)

    # 4. Send via SES
    response = ses.send_raw_email(
        Source=SENDER_EMAIL,
        Destinations=recipients,
        RawMessage={'Data': msg.as_bytes()}
    )
    message_id = response['MessageId']
    print(f"Email sent: sector={sector}, week={week}, recipients={recipients}, message_id={message_id}")
    return {'status': 'ok', 'recipient': recipients[0], 'message_id': message_id, 'email_sent': True}


